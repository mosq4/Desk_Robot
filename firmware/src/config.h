/**
 * @file config.h
 * @brief ESP32 统一参数配置 (集中所有可调参数, 网页端通过 /api/config 同步读取)
 *
 *  注意: 画布/绘画区参数须与 STM32 robot_config.h 保持一致。
 *
 *  本文件是整个 ESP32 固件的参数中心，所有可调参数集中在此处管理。
 *  修改本文件中的参数后，网页端通过 /api/config 接口可自动同步最新值，
 *  无需手动修改网页代码。
 */
#pragma once

/* ================================================================
 * WiFi AP（接入点）配置
 * ESP32 作为 WiFi 热点，手机/电脑连接此热点后可访问 Web 控制台
 * ================================================================ */
#define AP_SSID              "DrawingRobot"   /* WiFi 热点名称（SSID） */
#define AP_PASS              "12345678"       /* WiFi 热点密码（至少 8 位） */

/* ================================================================
 * STM32 串口通信配置
 * ESP32 通过 UART1 与下位机 STM32 进行板间通信
 * 接线说明：
 *   - ESP32 GPIO6 (RX) <- STM32 PB10 (USART3_TX)
 *   - ESP32 GPIO7 (TX) -> STM32 PB11 (USART3_RX)
 *   - GND 共地（必须共地，否则串口通信不稳定）
 * ================================================================ */
#define STM32_RX_PIN         6        /* ESP32 接收引脚（接 STM32 TX） */
#define STM32_TX_PIN         7        /* ESP32 发送引脚（接 STM32 RX） */
#define STM32_BAUD           115200   /* 串口波特率：115200 bps（8N1 格式） */

/* ================================================================
 * 通信与流控参数
 * 控制 G-code 下发流量和 ACK 超时机制
 * ================================================================ */
#define MAX_PROG_LINES       600      /* 单次缓存 G-code 最大行数（防止内存溢出） */
#define ACK_TIMEOUT_MS       600      /* 等待 STM32 ACK 回复的超时时间（毫秒） */
#define STATUS_STALE_MS      1500     /* 状态帧失联判定阈值（超过此时间未收到状态帧视为失联） */

/* ================================================================
 * 桌面上位机 TCP 通信配置
 * ESP32 同时提供 TCP 服务（供桌面 PyQt5 上位机连接），
 * 与网页端互斥：TCP 连接存在期间，网页的写接口(/api/ctl、/api/gcode) 返回占用。
 * ================================================================ */
#define TCP_PORT             8080     /* 桌面上位机 TCP 服务端口 */
#define TCP_GCODE_MAX_LINE   160      /* TCP 单行 G-code 最大长度（含 \n） */

/* ================================================================
 * 笛卡尔点动参数
 * 用于网页方向键控制末端 X/Y 方向移动
 * 注意：速度上限须与 STM32 端 JOG_SPEED_CAP 一致，末端速度上限为 3cm/s
 * ================================================================ */
#define JOG_SPEED_MIN_MM_S   5.0f     /* 点动最小速度（mm/s），对应滑杆最小值 */
#define JOG_SPEED_MAX_MM_S   30.0f    /* 点动最大速度（mm/s），对应滑杆最大值 */
#define JOG_SPEED_DEF_MM_S   10.0f    /* 点动默认速度（mm/s），网页启动时的初始速度 */

/* ================================================================
 * 单电机调试参数（CMD_JOG_MOTOR 0x0B）
 * 用于上位机调试模式：单独控制电机 1/2 正反转
 * 注意：速度上限须与 STM32 端单电机调试速度限制一致
 * ================================================================ */
#define JOG_MOTOR_SPEED_MAX  5.0f     /* 单电机调试速度上限（rad/s） */

/* ================================================================
 * A4 画布与绘画区域参数
 * 注意：以下参数必须与 STM32 robot_config.h 保持完全一致
 *       否则会出现坐标映射错误，导致绘画位置偏移
 * ================================================================ */
#define A4_W_MM              210.0f   /* A4 纸短边宽度（毫米），标准 A4 尺寸 */
#define A4_H_MM              297.0f   /* A4 纸长边高度（毫米），标准 A4 尺寸 */
#define CANVAS_PX_PER_MM     2.0f     /* 网页画板像素比例：每毫米对应 2 像素
                                          画板像素尺寸 = A4_W_MM * CANVAS_PX_PER_MM
                                          例如：210mm * 2px/mm = 420px 宽度 */
#define DRAW_MARGIN_MM       10.0f    /* 绘画区域四周留白（毫米），防止画笔超出纸面边缘 */
#define DRAW_FEED_MM_MIN     1500.0f  /* 默认进给速度（mm/min）= 25mm/s
                                          换算：1500 mm/min ÷ 60 = 25 mm/s
                                          不超过 3cm/s（30mm/s）的末端安全限速 */
